-- ---------------------------------------------------------------- helpers ---
create or replace function public.semver_arr(v text) returns int[]
language sql immutable as $$
  select coalesce(string_to_array(regexp_replace(split_part(coalesce(v,'0'),'-',1),'[^0-9.]','','g'),'.')::int[], '{0}')
$$;

-- ----------------------------------------------------------------- admins ---
create table if not exists public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  email      text not null,
  role       text not null check (role in ('owner','admin','support','viewer')),
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;

create or replace function public.admin_rank(r text) returns int
language sql immutable as $$
  select case r when 'owner' then 4 when 'admin' then 3 when 'support' then 2 when 'viewer' then 1 else 0 end
$$;

create or replace function public.is_admin(min_role text default 'viewer') returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins a
                 where a.user_id = auth.uid()
                   and public.admin_rank(a.role) >= public.admin_rank(min_role))
$$;

