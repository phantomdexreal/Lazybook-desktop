-- ------------------------------------------------- effective-flags helper ---
create or replace function public.effective_features(p_license text) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(p.features,'{}'::jsonb) || coalesce(l.features_override,'{}'::jsonb)
  from public.licenses l left join public.plans p on p.id = l.plan_id
  where l.license_key = p_license
$$;

-- ------------------------------------------------ PUBLIC RPC #1: resolve ---
create or replace function public.resolve_license(p_license_key text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare l public.licenses; pr public.supabase_projects;
begin
  select * into l from public.licenses where license_key = upper(trim(p_license_key));
  if not found then return jsonb_build_object('ok', false, 'error', 'License not found'); end if;
  if not l.is_active then return jsonb_build_object('ok', false, 'error', coalesce(l.suspended_reason,'License is inactive')); end if;
  if l.expires_at is not null and l.expires_at < now() then return jsonb_build_object('ok', false, 'error', 'License expired'); end if;
  select * into pr from public.supabase_projects where id = l.project_id;
  if not found or pr.status not in ('active','paused') then return jsonb_build_object('ok', false, 'error', 'No data project assigned to this license yet'); end if;
  return jsonb_build_object('ok', true, 'company_name', l.company_name, 'is_active', l.is_active,
     'expires_at', l.expires_at, 'project_url', pr.url, 'project_anon_key', pr.anon_key);
end $$;

-- ---------------------------------------------- PUBLIC RPC #2: bootstrap ---
-- One call returns everything an app needs on start: status, flags, theme list,
-- branding, update info, announcements. Also records a heartbeat.
create or replace function public.app_bootstrap(
  p_license_key text, p_app text, p_app_version text, p_device_id text, p_platform text default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  l public.licenses; pr public.supabase_projects; flags jsonb; br jsonb; gbr jsonb;
  rel public.app_releases; upd jsonb := null; themes jsonb; anns jsonb;
begin
  select * into l from public.licenses where license_key = upper(trim(p_license_key));
  if not found then return jsonb_build_object('ok', false, 'error', 'License not found'); end if;
  if not l.is_active then return jsonb_build_object('ok', false, 'error', coalesce(l.suspended_reason,'License is inactive')); end if;
  if l.expires_at is not null and l.expires_at < now() then return jsonb_build_object('ok', false, 'error', 'License expired', 'expired', true); end if;
  select * into pr from public.supabase_projects where id = l.project_id;
  flags := public.effective_features(l.license_key);

  -- heartbeat
  insert into public.license_health(license_key, device_id, app, app_version, platform, last_seen_at)
  values (l.license_key, p_device_id, p_app, p_app_version, p_platform, now())
  on conflict (license_key, device_id, app)
  do update set app_version = excluded.app_version, platform = excluded.platform, last_seen_at = now();

  -- update info: newest published stable release this device is bucketed into
  select * into rel from public.app_releases r
   where r.app = p_app and r.status = 'published' and r.channel = 'stable'
     and (abs(hashtext(coalesce(p_device_id,''))) % 100) < r.rollout_pct
   order by public.semver_arr(r.version) desc limit 1;
  if found then
    upd := jsonb_build_object(
      'latest', rel.version, 'notes', rel.notes, 'download_url', rel.download_url, 'sha256', rel.sha256,
      'min_supported', rel.min_supported_version,
      'update_available', public.semver_arr(rel.version) > public.semver_arr(p_app_version),
      'must_update', rel.force_update and public.semver_arr(rel.version) > public.semver_arr(p_app_version)
                     or (rel.min_supported_version is not null
                         and public.semver_arr(p_app_version) < public.semver_arr(rel.min_supported_version)));
  end if;

  -- themes this license may use (versions only; full JSON via get_themes)
  select coalesce(jsonb_agg(jsonb_build_object('slug', t.slug, 'version', t.version, 'name', t.name)), '[]'::jsonb) into themes
    from public.themes t
   where t.is_active and (l.theme_policy->>'allowed' = 'all'
         or t.slug in (select jsonb_array_elements_text(l.theme_policy->'allowed')));

  -- branding: license-specific overrides global
  select jsonb_build_object('version', b.version, 'assets', b.assets, 'app_name', b.app_name) into br
    from public.branding_sets b where b.scope='license' and b.license_key = l.license_key and b.is_active
    order by b.version desc limit 1;
  select jsonb_build_object('version', b.version, 'assets', b.assets, 'app_name', b.app_name) into gbr
    from public.branding_sets b where b.scope='global' and b.is_active order by b.version desc limit 1;

  select coalesce(jsonb_agg(jsonb_build_object('id', a.id, 'title', a.title, 'body', a.body, 'severity', a.severity)), '[]'::jsonb) into anns
    from public.announcements a
   where a.is_active and a.starts_at <= now() and (a.ends_at is null or a.ends_at > now())
     and (a.audience->'apps' is null or a.audience->'apps' ? p_app);

  return jsonb_build_object(
    'ok', true, 'server_time', now(),
    'license', jsonb_build_object('company_name', l.company_name, 'expires_at', l.expires_at,
               'max_devices', l.max_devices, 'max_companies', l.max_companies),
    'target', jsonb_build_object('url', pr.url, 'anon_key', pr.anon_key),
    'features', flags,
    'theme_policy', l.theme_policy, 'themes', themes,
    'branding', coalesce(br, gbr, '{}'::jsonb),
    'update', upd, 'announcements', anns,
    'config', (select coalesce(jsonb_object_agg(c.key, c.value), '{}'::jsonb) from public.app_config c));
end $$;

-- ------------------------------------------------ PUBLIC RPC #3: get_themes ---
create or replace function public.get_themes(p_license_key text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare l public.licenses;
begin
  select * into l from public.licenses where license_key = upper(trim(p_license_key)) and is_active;
  if not found then return '[]'::jsonb; end if;
  return (select coalesce(jsonb_agg(jsonb_build_object('slug', t.slug, 'version', t.version, 'json', t.json)), '[]'::jsonb)
            from public.themes t
           where t.is_active and (l.theme_policy->>'allowed' = 'all'
                 or t.slug in (select jsonb_array_elements_text(l.theme_policy->'allowed'))));
end $$;

-- ------------------------------ PUBLIC RPC #4: CI publishes a release -------
-- Called by GitHub Actions with a shared CI secret stored in Vault/ENV of an
-- Edge Function (preferred). Kept here as a SECURITY DEFINER fallback that only
-- admins may call via PostgREST.
create or replace function public.publish_release(
  p_app text, p_version text, p_channel text, p_notes text, p_download_url text,
  p_sha256 text, p_repo text, p_tag text, p_release_id bigint
) returns uuid language plpgsql security definer set search_path = public as $$
declare rid uuid;
begin
  if not public.is_admin('admin') then raise exception 'forbidden'; end if;
  insert into public.app_releases(app, version, channel, notes, download_url, sha256, github_repo, github_tag, github_release_id, status)
  values (p_app, p_version, coalesce(p_channel,'stable'), p_notes, p_download_url, p_sha256, p_repo, p_tag, p_release_id, 'draft')
  on conflict (app, version, channel) do update
     set notes = excluded.notes, download_url = excluded.download_url, sha256 = excluded.sha256,
         github_tag = excluded.github_tag, github_release_id = excluded.github_release_id
  returning id into rid;
  return rid;
end $$;

