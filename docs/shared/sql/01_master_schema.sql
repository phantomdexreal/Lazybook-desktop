create or replace function public.submit_request(p_license_key text, p_kind text, p_payload jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.licenses where license_key = upper(trim(p_license_key)) and is_active) then
    return jsonb_build_object('ok', false, 'error', 'License not found');
  end if;
  if octet_length(coalesce(p_payload,'{}'::jsonb)::text) > 20000 then
    return jsonb_build_object('ok', false, 'error', 'Payload too large');
  end if;
  if (select count(*) from public.support_requests where license_key = upper(trim(p_license_key))
        and created_at > now() - interval '1 hour') >= 10 then
    return jsonb_build_object('ok', false, 'error', 'Too many requests, try later');
  end if;
  insert into public.support_requests(license_key, kind, payload)
  values (upper(trim(p_license_key)), p_kind, coalesce(p_payload,'{}'::jsonb));
  return jsonb_build_object('ok', true);
end $$;
grant execute on function public.submit_request(text,text,jsonb) to anon, authenticated;

